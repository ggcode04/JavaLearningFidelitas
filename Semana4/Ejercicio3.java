public class Ejercicio3 {

    public static void main(String[] args) {

        // Recorre las filas
        for (int fila = 1; fila <= 4; fila++) {

            // Recorre las columnas
            for (int columna = 1; columna <= 4; columna++) {

                // Imprime un asterisco
                System.out.print("*");
            }

            // Salto de línea al finalizar cada fila
            System.out.println();
        }

    }

}